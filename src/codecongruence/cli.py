def ensure_gitignore_entry(repo_root: Path, entry: str = ".codecongruence") -> bool:
    """Add ``entry`` to ``.gitignore`` if absent.

    Args:
        repo_root: Root directory containing (or to contain) the ``.gitignore``.
        entry: The line to add (default: ``".codecongruence"``).

    Returns:
        ``True`` if the entry was added, ``False`` if it was already present.
    """
    gitignore = repo_root / ".gitignore"
    if gitignore.exists():
        text = gitignore.read_text(encoding="utf-8")
        if any(line.strip() == entry for line in text.splitlines()):
            return False
        gitignore.write_text(text.rstrip("\n") + f"\n{entry}\n", encoding="utf-8")
    else:
        gitignore.write_text(f"{entry}\n", encoding="utf-8")
    return True


async def make_embedder(
    config: CodeCongruenceConfig,
    repo_root: Path,
    backend: BackendRequest | None = None,
) -> Embedder:
    """Build the run's :class:`Embedder` with a worktree-aware vector cache.

    The writable vector cache lives in the current worktree
    (``<repo_root>/.codecongruence``). The primary worktree's cache is layered
    underneath as a read-only *base*, so a linked git worktree reuses the
    primary's warm embeddings instead of cold-starting on a fresh checkout. The
    :class:`Embedder` ignores the base when it resolves to the local cache —
    i.e. when this run *is* the primary worktree, which then owns its cache
    directly. Both caches are content-hash keyed, so a base entry is valid for
    any worktree.

    Args:
        config: Loaded configuration for this run.
        repo_root: Root of the current worktree.
        backend: ``--backend`` override; ``None`` uses ``config.backend``.

    Returns:
        A configured :class:`Embedder` ready to embed.
    """
    resolved = resolve_backend(backend or config.backend, config.model)
    local_cache_dir = repo_root / ".codecongruence"
    main_root = await main_worktree_root(cwd=repo_root)
    base_cache_dir = None if main_root is None else main_root / ".codecongruence"
    model_cache_dir = Path.home() / ".cache" / "codecongruence"
    return Embedder(
        model_name=config.model,
        resolved=resolved,
        cache_dir=local_cache_dir,
        base_cache_dir=base_cache_dir,
        model_cache_dir=model_cache_dir,
        threads=config.threads,
        embed_batch_size=config.embed_batch_size,
        cache_ttl_days=config.cache_ttl_days,
    )


def version_callback(value: bool) -> None:
    """Print the version and exit when ``--version`` is passed.

    Args:
        value: ``True`` when the ``--version`` flag was supplied.

    Raises:
        typer.Exit: After printing the version, to stop CLI processing.
    """
    if value:
        typer.echo(f"codecongruence {resolve_version()}")
        raise typer.Exit


def purge_models_callback(value: bool) -> None:
    """Delete the downloaded model cache and exit when ``--purge-models`` is passed.

    Args:
        value: ``True`` when the ``--purge-models`` flag was supplied.

    Raises:
        typer.Exit: After deleting the cache, to stop CLI processing.
    """
    if value:
        import shutil  # noqa: PLC0415

        cache = Path.home() / ".cache" / "codecongruence"
        if cache.exists():
            shutil.rmtree(cache)
            typer.echo(f"removed {cache}")
        else:
            typer.echo(f"nothing to remove ({cache} does not exist)")
        raise typer.Exit


@app.callback(invoke_without_command=True)
def main(
    ctx: typer.Context,
    files: Annotated[
        list[Path] | None,
        typer.Argument(
            help=(
                "Check exactly these files (whole files; missing, deleted or "
                "out-of-repo paths are skipped). Omit to check the staged diff."
            ),
            show_default=False,
        ),
    ] = None,
    rule: Annotated[
        str | None,
        typer.Option(
            "--rule",
            "-r",
            help=(
                "Run a single rule by id (docstring_vs_body) or code (D001), "
                "even if disabled in config. Unknown rules exit 2."
            ),
        ),
    ] = None,
    config_path: Annotated[
        Path | None,
        typer.Option(
            "--config",
            "-c",
            help=(
                "Path to a TOML config — either a stand-alone codecongruence.toml "
                r"or a pyproject.toml with a \[tool.codecongruence] section. "
                "Auto-detected. Overrides repo-root discovery."
            ),
            exists=True,
        ),
    ] = None,
    all_files: Annotated[
        bool,
        typer.Option("--all", help="Scan the whole repo, not just staged changes."),
    ] = False,
    output_format: Annotated[
        OutputFormat,
        typer.Option("--format", "-f", help="Output format."),
    ] = OutputFormat.text,
    verbose: Annotated[
        bool,
        typer.Option(
            "--verbose", "-v", help="Print the full violation table and an OK line on success."
        ),
    ] = False,
    include_unstaged: Annotated[
        bool,
        typer.Option("--include-unstaged", help="Also check unstaged changes."),
    ] = False,
    update_baseline: Annotated[
        bool,
        typer.Option(
            "--update-baseline",
            help=(
                "Save all current violations as the new baseline and exit 0. "
                "Commit .codecongruence/.codecongruence-baseline.json to share with the team."
            ),
        ),
    ] = False,
    prune_baseline_flag: Annotated[
        bool,
        typer.Option(
            "--prune-baseline",
            help=(
                "Remove baseline entries whose violation no longer exists (only entries "
                "for files checked and rules run in this invocation). Never adds entries. "
                "Exits non-zero only if unsuppressed violations remain. "
                "Mutually exclusive with --update-baseline."
            ),
        ),
    ] = False,
    backend: Annotated[
        BackendChoice | None,
        typer.Option(
            "--backend",
            help=(
                "Embedding engine, overriding the config: auto (MLX on Apple Silicon "
                "when installed, else ONNX), mlx (error if unavailable) or onnx."
            ),
        ),
    ] = None,
    debug: Annotated[
        bool,
        typer.Option(
            "--debug",
            help="Emit per-check similarity scores and pass/fail to stderr.",
        ),
    ] = False,
    _purge_models: Annotated[
        bool,
        typer.Option(
            "--purge-models",
            callback=purge_models_callback,
            is_eager=True,
            help="Delete the model cache (~/.cache/codecongruence) and exit.",
        ),
    ] = False,
    _version: Annotated[
        bool,
        typer.Option(
            "--version",
            callback=version_callback,
            is_eager=True,
            help="Print version and exit.",
        ),
    ] = False,
) -> None:
    """Check the staged diff (default), the whole repo (``--all``) or the given FILES.

    Raises:
        Exit: With code ``1`` when any error-severity violation is found, or
            ``2`` when ``--rule`` names an unknown rule id.
    """
    if ctx.invoked_subcommand is not None:
        return

    # Resolve against the invocation directory now: ``run`` chdirs to the repo root.
    explicit_files = [Path.cwd() / f for f in files] if files else None
    exit_code = asyncio.run(
        run(
            explicit_files=explicit_files,
            rule=rule,
            config_path=config_path,
            all_files=all_files,
            output_format=output_format,
            verbose=verbose,
            include_unstaged=include_unstaged,
            update_baseline=update_baseline,
            prune_stale=prune_baseline_flag,
            backend=backend.value if backend else None,
            debug=debug,
        )
    )
    raise typer.Exit(exit_code)


@app.command(name="init")
def init_cmd(
    path: Annotated[
        Path | None,
        typer.Option("--path", help="Where to write the config (default: repo root)."),
    ] = None,
    force: Annotated[
        bool,
        typer.Option("--force", help="Overwrite an existing config."),
    ] = False,
    no_download: Annotated[
        bool,
        typer.Option("--no-download", help="Skip model download (also skips pre-embedding)."),
    ] = False,
    no_embed: Annotated[
        bool,
        typer.Option("--no-embed", help="Download the model but skip pre-embedding all files."),
    ] = False,
) -> None:
    """Write a default ``codecongruence.toml`` and warm up the embedding model.

    Also installs AI-tool context files from the bundled ``agents/`` directory
    so Claude Code, Cursor, and OpenAI Codex know how to interpret and fix
    codecongruence violations:

    - ``.claude/skills/codecongruence/SKILL.md``
    - ``.cursor/rules/codecongruence.mdc``
    - ``AGENTS.md`` (section appended or file created)

    By default this also downloads the embedding model and pre-embeds every
    tracked file so the first ``git commit`` check is instant. Use
    ``--no-download`` to skip both, or ``--no-embed`` to download the model
    without pre-embedding.

    Args:
        path: Output path for the config file (default: repo root).
        force: If True, overwrite an existing config and AI context files.
        no_download: Skip model download and pre-embedding entirely.
        no_embed: Download model but skip pre-embedding tracked files.

    Raises:
        Exit: With code ``1`` when a config already exists and ``--force`` was not passed.
    """
    repo_root = asyncio.run(current_repo_root())
    # Resolve a user-supplied relative --path against the invocation directory
    # before anchoring at the repo root (pre-embedding reads root-relative paths).
    target = (path or default_config_path(repo_root)).resolve()
    os.chdir(repo_root)
    if target.exists() and not force:
        typer.echo(f"refusing to overwrite {target} (pass --force)")
        raise typer.Exit(code=1)
    target.write_text(DEFAULT_TOML, encoding="utf-8")
    typer.echo(f"wrote {target}")
    if ensure_gitignore_entry(target.parent):
        typer.echo("added .codecongruence to .gitignore")

    for ai_path, written in write_ai_context_files(repo_root, force=force):
        rel = ai_path.relative_to(repo_root) if ai_path.is_relative_to(repo_root) else ai_path
        if written:
            typer.echo(f"wrote {rel}")
        else:
            typer.echo(f"skipped {rel} (already exists; use --force to overwrite)")

    if no_download:
        return

    asyncio.run(init_setup(no_embed=no_embed))


async def init_setup(*, no_embed: bool) -> None:
    """Download the model and warm the embedding cache for ``init``.

    Args:
        no_embed: When ``True``, skip the initial full-repo embedding pass and
            only ensure the model is downloaded and ready.

    Raises:
        Exit: With code ``2`` when the configured backend is unavailable.
    """
    from rich.console import Console  # noqa: PLC0415
    from rich.progress import (  # noqa: PLC0415
        BarColumn,
        MofNCompleteColumn,
        Progress,
        SpinnerColumn,
        TextColumn,
    )

    console = Console()

    repo_root = await current_repo_root()
    config = load_config(repo_root=repo_root)
    try:
        embedder = await make_embedder(config, repo_root)
    except BackendUnavailableError as exc:
        typer.echo(f"codecongruence: {exc}", err=True)
        raise typer.Exit(2) from exc

    # Model download may emit fastembed / huggingface_hub tqdm output to stderr.
    # Print a plain line before so it doesn't interleave with any live display.
    console.print(f"[dim]downloading model {config.model!r}…[/dim]")
    await embedder.warm_up()
    console.print("[green]✓[/green] model ready")

    if no_embed:
        return

    runner = RuleRunner(config, embedder)
    changed = await runner.gather_changed(all_files=True)
    before = embedder.cache_size

    with Progress(
        SpinnerColumn(),
        TextColumn("[progress.description]{task.description}"),
        BarColumn(),
        MofNCompleteColumn(),
        console=console,
        transient=False,
    ) as progress:
        task = progress.add_task(f"embedding {len(changed)} file(s)", total=len(changed))
        for cf in changed:
            await runner.run(pre_gathered=[cf])
            progress.advance(task)

    embedder.save(force_cleanup=True)
    added = embedder.cache_size - before
    console.print(f"[green]✓[/green] cached {embedder.cache_size} embedding(s) ({added} new)")


def report_stale(stale: Sequence[BaselineEntry]) -> None:
    """Print each stale baseline entry plus the prune hint to stderr.

    Args:
        stale: Entries returned by :func:`find_stale`; prints nothing when empty.
    """
    for entry in stale:
        suffix = f" - {entry.message}" if entry.message else ""
        typer.echo(
            f"stale baseline entry: {entry.rule_id} {entry.file_path}:{entry.line}{suffix}",
            err=True,
        )
    if stale:
        typer.echo(
            f"codecongruence: {len(stale)} stale baseline entr{'y' if len(stale) == 1 else 'ies'} "
            "(violation resolved); run --prune-baseline to remove resolved entries",
            err=True,
        )


def enable_debug_logging() -> None:
    """Route ``codecongruence`` debug records to stderr for ``--debug``."""
    handler = logging.StreamHandler()
    handler.setFormatter(logging.Formatter("%(name)s  %(message)s"))
    logger = logging.getLogger("codecongruence")
    logger.setLevel(logging.DEBUG)
    logger.addHandler(handler)


def flag_conflict(
    *,
    explicit_files: bool,
    all_files: bool,
    include_unstaged: bool,
    update_baseline: bool,
    prune_stale: bool,
) -> str | None:
    """Describe the first ambiguous flag combination, or return ``None`` when valid.

    Explicit FILES already fix the scope, so ``--all`` / ``--include-unstaged``
    are ambiguous with them, and ``--update-baseline`` would rewrite the whole
    baseline from a partial run.

    Args:
        explicit_files: FILES were given on the command line.
        all_files: ``--all`` was given.
        include_unstaged: ``--include-unstaged`` was given.
        update_baseline: ``--update-baseline`` was given.
        prune_stale: ``--prune-baseline`` was given.

    Returns:
        The error message for the conflict, or ``None``.
    """
    if update_baseline and prune_stale:
        return "--update-baseline and --prune-baseline are mutually exclusive"
    if not explicit_files:
        return None
    for flag, given in (
        ("--all", all_files),
        ("--include-unstaged", include_unstaged),
        ("--update-baseline", update_baseline),
    ):
        if given:
            return f"{flag} with explicit FILES is ambiguous; pass either FILES or {flag}"
    return None


async def run(
    *,
    rule: str | None,
    config_path: Path | None,
    all_files: bool,
    output_format: OutputFormat,
    verbose: bool,
    include_unstaged: bool,
    update_baseline: bool = False,
    prune_stale: bool = False,
    backend: BackendRequest | None = None,
    debug: bool = False,
    explicit_files: Sequence[Path] | None = None,
) -> int:
    """Run the selected rules over the changed files and report violations.

    Args:
        explicit_files: Check exactly these files (whole-file scope) instead of
            the staged diff. ``None`` keeps the git-derived scope.
        rule: Single rule id to run, or ``None`` to run every default rule.
        config_path: Explicit config file, or ``None`` to auto-discover.
        all_files: Scan every tracked file instead of only the staged diff.
        output_format: ``text`` or ``json`` reporter selection.
        verbose: Print an OK line and the violation table on success.
        include_unstaged: Also check unstaged working-tree changes.
        update_baseline: Save all current violations as the new baseline, then exit.
        prune_stale: Drop stale baseline entries (resolved violations) from the baseline file.
        backend: ``--backend`` override of the configured embedding engine.
        debug: Emit per-rule debug logging to stderr.

    Returns:
        Process exit code — ``0`` when clean, ``1`` when violations are found,
        and ``2`` when the flags conflict or the rule selection or an explicit
        backend is invalid.
    """
    conflict = flag_conflict(
        explicit_files=explicit_files is not None,
        all_files=all_files,
        include_unstaged=include_unstaged,
        update_baseline=update_baseline,
        prune_stale=prune_stale,
    )
    if conflict is not None:
        typer.echo(f"codecongruence: {conflict}", err=True)
        return 2

    if debug:
        enable_debug_logging()

    repo_root = await current_repo_root()
    config = load_config(path=config_path, repo_root=repo_root)
    # Rules read changed-file paths relative to the repo root, so anchor the
    # process there — otherwise running from a subdirectory checks nothing.
    os.chdir(repo_root)
    try:
        embedder = await make_embedder(config, repo_root, backend)
    except BackendUnavailableError as exc:
        typer.echo(f"codecongruence: {exc}", err=True)
        return 2
    typer.echo(f"codecongruence: embedding backend: {embedder.resolved.describe()}", err=True)
    runner = RuleRunner(config, embedder)
    try:
        runner.select_rules(rule)
    except UnknownRuleError as exc:
        typer.echo(f"codecongruence: {exc}", err=True)
        return 2
    changed = await runner.gather_changed(
        explicit_files=explicit_files, all_files=all_files, include_unstaged=include_unstaged
    )

    if verbose and output_format is OutputFormat.text:
        from rich.console import Console  # noqa: PLC0415

        selected_preview = runner.select_rules(rule)
        Console().print(
            f"[dim]codecongruence: scanning {len(changed)} file(s) "
            f"with {len(selected_preview)} rule(s)…[/dim]"
        )

    result = await runner.run(
        only=rule,
        pre_gathered=changed,
        file_list=explicit_files is not None,
    )

    embedder.save(force_cleanup=all_files)

    if update_baseline:
        bl_path = baseline_path(repo_root)
        save_baseline(result.violations, bl_path)
        typer.echo(
            f"codecongruence: saved {len(result.violations)} violation(s) to "
            f"{bl_path.relative_to(repo_root)}"
        )
        if result.violations:
            typer.echo(
                "Commit .codecongruence/.codecongruence-baseline.json to share across the team. "
                "Future runs will only fail on new violations."
            )
        return 0

    bl = load_baseline(baseline_path(repo_root))
    suppressed = 0
    stale: tuple[BaselineEntry, ...] = ()
    if bl is not None:
        stale = find_stale(bl, result, full_scan=all_files, file_list=explicit_files is not None)
        result, suppressed = apply_baseline(result, bl)
    if prune_stale and stale:
        removed = prune_baseline(baseline_path(repo_root), stale)
        typer.echo(
            f"codecongruence: pruned {removed} stale baseline entr{'y' if removed == 1 else 'ies'}",
            err=True,
        )
        stale = ()

    if output_format is OutputFormat.json:
        JsonReporter().report(result, stale_baseline=stale, backend=embedder.resolved)
    else:
        TextReporter(verbose=verbose).report(
            result, given_paths=None if explicit_files is None else len(explicit_files)
        )
        if suppressed > 0:
            from rich.console import Console  # noqa: PLC0415

            Console().print(
                f"[dim]{suppressed} violation(s) suppressed by baseline "
                "(run --update-baseline to reset)[/dim]"
            )
        report_stale(stale)

    return 0 if result.ok and not stale else 1


