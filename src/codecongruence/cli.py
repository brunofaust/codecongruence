class OutputFormat(StrEnum):
    """Output format for violation reporting."""

    text = "text"
    json = "json"


app = typer.Typer(
    name="codecongruence",
    no_args_is_help=False,
    add_completion=False,
    help="Semantic pre-commit checks. Keep your repo congruent — one story, not many.",
)


